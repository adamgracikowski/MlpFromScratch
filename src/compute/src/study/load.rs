//! Loading a study: parsing, validation and checking every generated config.

use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};

use miette::NamedSource;

use super::{RunError, RunSpec, STUDY_FILE_NAME, StudyConfig, StudyError, expand, validate};
use crate::config::{CONFIG_FILE_NAME, ConfigError, IssueDiagnostic, diagnostics, load_from_str};

/// First lines of every generated `config.toml`.
const GENERATED_HEADER: &str = "# Generated by `compute generate` from ../../../study.toml.\n\
                                # Edit the study and generate the runs again instead of this file.\n\n";

/// A study whose generated configs all passed validation.
#[derive(Debug)]
pub struct Study {
    /// The study directory.
    pub dir: PathBuf,
    /// The parsed `study.toml`.
    pub config: StudyConfig,
    /// Every run, in the order of [`expand`].
    pub runs: Vec<GeneratedRun>,
}

/// A run of a study with the text of its `config.toml`.
#[derive(Debug)]
pub struct GeneratedRun {
    /// Variant, seed and directory of the run.
    pub spec: RunSpec,
    /// Text of `config.toml`: a header and the config with all values,
    /// including the defaults.
    pub text: String,
    /// Non-fatal issues of the config.
    pub warnings: Vec<IssueDiagnostic>,
}

/// Reads `study.toml` from `study_dir`, validates it, expands it into runs
/// and checks the config of every run as `train` would, including the
/// headers of the dataset files.
///
/// All problems of `study.toml` are reported together, each pointing at its
/// line. Invalid generated configs are reported once per variant.
pub fn load_study(study_dir: &Path) -> Result<Study, StudyError> {
    let path = study_dir.join(STUDY_FILE_NAME);
    let text = fs::read_to_string(&path).map_err(|source| StudyError::Io {
        path: path.clone(),
        source,
    })?;
    let src = NamedSource::new(path.display().to_string(), text.clone());
    let config: StudyConfig = toml::from_str(&text).map_err(|err| StudyError::Parse {
        message: err.message().to_owned(),
        src: src.clone(),
        span: err.span().map(Into::into),
    })?;

    let issues = validate(&config);
    let error_count = issues.iter().filter(|issue| issue.is_error()).count();
    if error_count > 0 {
        return Err(StudyError::Invalid {
            path,
            error_count,
            issues: diagnostics(issues, &src),
        });
    }

    let mut runs = Vec::new();
    let mut errors: Vec<(String, RunError)> = Vec::new();
    let mut failed = HashSet::new();
    for spec in expand(&config) {
        if failed.contains(&spec.variant) {
            continue;
        }
        match generate(study_dir, &spec) {
            Ok((text, warnings)) => runs.push(GeneratedRun {
                spec,
                text,
                warnings,
            }),
            Err(err) => {
                failed.insert(spec.variant.clone());
                let issues = issue_messages(&err);
                match errors.iter_mut().find(|(other, _)| *other == issues) {
                    Some((_, error)) => error.same_in.push(spec.variant),
                    None => errors.push((
                        issues,
                        RunError {
                            variant: spec.variant,
                            seed: spec.seed,
                            same_in: Vec::new(),
                            config_error: err,
                        },
                    )),
                }
            }
        }
    }
    let errors: Vec<RunError> = errors.into_iter().map(|(_, error)| error).collect();
    if !errors.is_empty() {
        return Err(StudyError::Runs { errors });
    }
    Ok(Study {
        dir: study_dir.to_path_buf(),
        config,
        runs,
    })
}

/// The error messages of a config error without file paths and warnings, to
/// group variants that fail for the same reason.
fn issue_messages(err: &ConfigError) -> String {
    match err {
        ConfigError::Invalid { issues, .. } => issues
            .iter()
            .filter(|issue| issue.issue().is_error())
            .map(|issue| issue.issue().to_string())
            .collect::<Vec<_>>()
            .join("\n"),
        other => other.to_string(),
    }
}

/// Checks the config of `spec` and renders the text of its `config.toml`.
///
/// Errors point into the merged table as TOML. The rendered text is loaded
/// again so that warnings point at the lines of the written file.
fn generate(
    study_dir: &Path,
    spec: &RunSpec,
) -> Result<(String, Vec<IssueDiagnostic>), ConfigError> {
    let path = study_dir.join(&spec.dir).join(CONFIG_FILE_NAME);
    let raw = toml::to_string(&spec.config).expect("a parsed TOML table serializes");
    let loaded = load_from_str(path.clone(), raw)?;
    let body = toml::to_string(&loaded.config).expect("a valid config serializes");
    let text = format!("{GENERATED_HEADER}{body}");
    let rendered = load_from_str(path, text.clone())?;
    Ok((text, rendered.warnings))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::ExperimentConfig;
    use crate::study::fixtures::{STUDY, study_dir};

    #[test]
    fn loads_valid_study() {
        let dir = study_dir(STUDY);
        let study = load_study(dir.path()).unwrap();
        assert_eq!(study.runs.len(), 8);
        let run = &study.runs[2];
        assert!(run.text.starts_with("# Generated by `compute generate`"));
        let config: ExperimentConfig = toml::from_str(&run.text).unwrap();
        assert_eq!(config.model.hidden_layers, [8, 8]);
        assert_eq!(config.training.seed, 1);
    }

    #[test]
    fn reports_missing_study() {
        let dir = tempfile::TempDir::new().unwrap();
        let err = load_study(dir.path()).unwrap_err();
        assert!(matches!(err, StudyError::Io { .. }));
    }

    #[test]
    fn reports_parse_error_with_span() {
        let dir = study_dir(&STUDY.replace("seeds = [1, 2]", "seeds = \"many\""));
        let err = load_study(dir.path()).unwrap_err();
        let StudyError::Parse { span, .. } = err else {
            panic!("expected a parse error, got {err:?}");
        };
        assert!(span.is_some());
    }

    #[test]
    fn reports_invalid_values_at_study_lines() {
        let dir = study_dir(&STUDY.replace("seeds = [1, 2]", "seeds = []"));
        let err = load_study(dir.path()).unwrap_err();
        let StudyError::Invalid {
            error_count,
            issues,
            ..
        } = err
        else {
            panic!("expected validation errors, got {err:?}");
        };
        assert_eq!(error_count, 1);
        assert!(issues[0].offset().is_some());
    }

    #[test]
    fn groups_variants_with_the_same_invalid_config() {
        // Classification needs softmax, so every `identity` variant fails.
        let text = STUDY.replace(
            "key = \"model.hidden_layers\"\nvalues = [[], [8, 8]]",
            "key = \"model.output_activation\"\nvalues = [\"softmax\", \"identity\"]",
        );
        let dir = study_dir(&text);
        let err = load_study(dir.path()).unwrap_err();
        let StudyError::Runs { errors } = err else {
            panic!("expected invalid runs, got {err:?}");
        };
        let variants: Vec<(&str, u64)> = errors
            .iter()
            .map(|error| (error.variant.as_str(), error.seed))
            .collect();
        assert_eq!(variants, [("sigmoid__identity", 1)]);
        assert_eq!(errors[0].same_in, ["tanh__identity"]);
        assert!(matches!(
            errors[0].config_error,
            ConfigError::Invalid { .. }
        ));
        assert_eq!(
            StudyError::Runs { errors }.to_string(),
            "2 variant(s) of the study have an invalid config"
        );
    }
}
